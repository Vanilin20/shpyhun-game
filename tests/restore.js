const http = require('http');
const { spawn } = require('child_process');
const BASE = 'http://127.0.0.1:3999';
const post = b => new Promise(ok => { const d = JSON.stringify(b); const r = http.request(BASE + '/api', { method: 'POST', headers: { 'Content-Type': 'application/json', 'Content-Length': Buffer.byteLength(d) } }, res => { let s = ''; res.on('data', c => s += c); res.on('end', () => ok(JSON.parse(s))); }); r.on('error', () => ok({ err: 1 })); r.end(d); });
const get = (room, t) => new Promise(ok => http.get(`${BASE}/state?room=${room}&t=${t}`, r => { let s = ''; r.on('data', x => s += x); r.on('end', () => ok(JSON.parse(s))); }));
const wait = ms => new Promise(r => setTimeout(r, ms));
const assert = (c, m) => { console.log((c ? 'ok: ' : 'FAIL: ') + m); if (!c) process.exitCode = 1; };
let srv; const up = () => { srv = spawn('node', ['server.js'], { env: { ...process.env, PORT: 3999 }, stdio: 'ignore' }); return wait(600); };
(async () => {
  await up();
  const c = await post({ action: 'create', name: 'Іван', used: [] }); const room = c.room; const P = [c];
  for (const n of ['Оля', 'Петро', 'Марта']) P.push(await post({ room, action: 'join', name: n }));
  for (const p of P) await get(room, p.token);
  await post({ room, token: c.token, action: 'settings', settings: { drawing: false, items: false, scene: false, emoji: true, review: false, auction: false } });
  await post({ room, token: c.token, action: 'start' });
  for (const p of P) await post({ room, token: p.token, action: 'ready' });
  for (let _k = 0; _k < 12; _k++) for (const p of P) await post({ room, token: p.token, action: 'name', text: 'Агент ' + p.id.slice(0, 2) });
  await post({ room, token: c.token, action: 'next' });
  const before = await get(room, P[1].token);
  assert(before.phase === 'questions' && before.snap, 'допит, знімок є (' + before.snap.length + ' байт)');
  const loc = before.me.location || (await get(room, P[2].token)).me.location;
  srv.kill(); await wait(300); await up();
  assert((await get(room, P[1].token)).noRoom, 'після перезапуску кімнати нема');
  assert((await post({ room, action: 'restore', snap: before.snap.slice(0, -8) + 'AAAAAAA=' })).noRoom, 'підроблений знімок відхилено');
  assert((await post({ room, action: 'restore', snap: before.snap })).ok, 'кімнату відновлено');
  assert((await post({ room, action: 'restore', snap: before.snap })).ok, 'повторне відновлення — без шкоди');
  const after = await get(room, P[1].token);
  assert(after.phase === 'questions' && after.order.join() === before.order.join() && after.target === before.target, 'та сама фаза й черга');
  assert(after.me && after.me.id === P[1].id && after.players.every(p => p.char), 'токени й імена персонажів збереглись');
  const locs = await Promise.all(P.map(p => get(room, p.token)));
  assert(locs.filter(v => v.me.isSpy).length === 1 && locs.find(v => !v.me.isSpy).me.location === loc, 'шпигун і локація ті самі');
  assert(after.endsAt - Date.now() > 100000, 'таймер відновився (' + Math.round((after.endsAt - Date.now()) / 1000) + ' с)');
  assert(after.hostId === c.id && (await get(room, c.token)).amHost, 'ведучий той самий');
  await post({ room, token: c.token, action: 'next' });
  assert((await get(room, c.token)).idx === 1, 'гра йде далі');
  srv.kill(); process.exit();
})();
