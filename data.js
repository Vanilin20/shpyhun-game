function fits(need, theme) {
  const tags = ((THEME_FIT[theme] || [''])[0] || '').split(' ');
  return need.split(' ').filter(Boolean).every(t => t[0] === '!' ? !tags.includes(t.slice(1)) : tags.includes(t));
}
